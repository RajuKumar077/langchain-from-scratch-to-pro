"""
Lesson 03: Local Ollama Agent with MCP Tools (LCEL Function Calling Loop)
========================================================================
This lesson connects your **100% Local Ollama LLM** to the MCP tools
using LangChain's native function calling abstractions (`bind_tools`).

Key Concepts Learned:
1. Tool Binding: `llm.bind_tools(tools)` informs the local model about MCP capabilities.
2. Tool Calling Execution: Inspecting `AIMessage.tool_calls` generated by local Ollama.
3. Feedback Loop: Creating `ToolMessage` containing MCP execution results and passing
   them back to the model for final synthesis.
4. Tracing: Fully traceable in LangSmith with zero external API fees.
"""

import asyncio
import sys
from pathlib import Path

# 1. Environment & LangSmith Setup (MUST run before LangChain imports)
import config
config_info = config.setup_environment(verbose=False)

from langchain_ollama import ChatOllama
from langchain_core.messages import HumanMessage, AIMessage, ToolMessage
from langchain_mcp_adapters.client import MultiServerMCPClient
from langsmith import traceable, Client

server_script = Path(config.SERVERS_DIR) / "math_weather_server.py"

@traceable(name="MCP Local Agent Run", run_type="chain")
async def execute_agent_turn(llm_with_tools, tool_map, user_query: str):
    """Executes a full turn: Model -> MCP Tool Calls -> Model Final Answer."""
    print(f"\nUser Query: \"{user_query}\"")
    print("-" * 65)

    messages = [HumanMessage(content=user_query)]

    # 1. First model invocation
    print("[1] Invoking Local Ollama with MCP tool definitions...")
    ai_response: AIMessage = await llm_with_tools.ainvoke(messages)
    messages.append(ai_response)

    # 2. Check if model requested tool calls
    if not ai_response.tool_calls:
        print("[*] Model replied directly without calling tools:")
        print(f"    {ai_response.content}")
        return ai_response.content

    print(f"[2] Model requested {len(ai_response.tool_calls)} tool call(s):")
    for tc in ai_response.tool_calls:
        tool_name = tc["name"]
        tool_args = tc["args"]
        call_id = tc["id"]
        print(f"    -> Calling MCP Tool: '{tool_name}' with args {tool_args} (ID: {call_id})")

        if tool_name not in tool_map:
            raise ValueError(f"Model requested unknown tool '{tool_name}'")

        # Execute MCP tool
        tool_result = await tool_map[tool_name].ainvoke(tool_args)
        
        # Flatten content if returned as list of dict blocks
        if isinstance(tool_result, list) and len(tool_result) > 0 and isinstance(tool_result[0], dict):
            formatted_result = tool_result[0].get("text", str(tool_result))
        else:
            formatted_result = str(tool_result)

        print(f"       MCP Result: {formatted_result.strip()}")

        # Append ToolMessage to conversation
        messages.append(ToolMessage(content=formatted_result, tool_call_id=call_id))

    # 3. Second model invocation with tool outputs
    print("\n[3] Sending tool outputs back to Ollama for final response...")
    final_response = await llm_with_tools.ainvoke(messages)
    print("\n[Final Answer]:")
    print(final_response.content.strip())
    print("-" * 65)
    return final_response.content

async def run_ollama_mcp_agent():
    print("=" * 65)
    print(f" Lesson 03: Local Ollama ({config_info['ollama_model']}) + MCP Agent")
    print("=" * 65)

    # 1. Connect to MCP Server via stdio
    client = MultiServerMCPClient({
        "math_weather": {
            "transport": "stdio",
            "command": sys.executable,
            "args": [str(server_script.resolve())],
        }
    })

    print("[*] Loading tools from MCP Server...")
    tools = await client.get_tools()
    tool_map = {t.name: t for t in tools}
    print(f"[*] Available MCP tools: {list(tool_map.keys())}")

    # 2. Initialize local Ollama chat model
    llm = ChatOllama(
        model=config_info["ollama_model"],
        temperature=0.0,
    )

    # 3. Bind tools to local LLM
    llm_with_tools = llm.bind_tools(tools)

    # 4. Run test scenarios
    # Test 1: Math calculation
    await execute_agent_turn(
        llm_with_tools,
        tool_map,
        "What is 35 multiplied by 18, and what is 512 + 1024?",
    )

    # Test 2: Weather lookup
    await execute_agent_turn(
        llm_with_tools,
        tool_map,
        "What is the current weather condition and temperature in Tokyo?",
    )

    # Flush traces to LangSmith if active
    if config_info["tracing_enabled"]:
        try:
            Client().flush()
            print("[LangSmith] Flushed traces to online dashboard.")
        except Exception:
            pass

    print()
    print("=" * 65)
    print(" [SUCCESS] Lesson 03 completed successfully!")
    print("=" * 65)

if __name__ == "__main__":
    asyncio.run(run_ollama_mcp_agent())
