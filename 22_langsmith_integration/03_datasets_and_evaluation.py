"""
Lesson 03 - LangSmith Datasets & Automated Evaluations with Local Ollama
========================================================================
Goal:
  1. Programmatically create a ground-truth Evaluation Dataset in LangSmith.
  2. Evaluate responses generated by your LOCAL Ollama model (`qwen3:8b`).
  3. Define custom evaluator functions (key phrase verification, conciseness).
  4. Run `evaluate()` across the dataset and view benchmark results in LangSmith.

Run command:
  r:\\LangChain-Book\\.venv\\Scripts\\python.exe 03_datasets_and_evaluation.py
"""

import os
from config import setup_environment
from langsmith import Client, evaluate
from langsmith.evaluation import EvaluationResult
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from langchain_ollama import ChatOllama

setup_environment()

# ------------------------------------------------------------------------------
# 1. Initialize LangSmith Client & Dataset Creation
# ------------------------------------------------------------------------------
DATASET_NAME = "LangSmith QA Benchmark (Local Ollama)"

def create_or_get_dataset(client: Client):
    """Create evaluation dataset if it doesn't already exist."""
    if client.has_dataset(dataset_name=DATASET_NAME):
        print(f"[INFO] Dataset '{DATASET_NAME}' already exists.")
        return client.read_dataset(dataset_name=DATASET_NAME)

    print(f"[DATASET] Creating new dataset '{DATASET_NAME}'...")
    dataset = client.create_dataset(
        dataset_name=DATASET_NAME,
        description="Benchmark dataset for testing AI technical questions with local Ollama."
    )

    # Sample ground truth evaluation examples
    examples = [
        {
            "inputs": {"question": "What is LangSmith?"},
            "outputs": {"expected": "A platform for building, testing, evaluating, and monitoring LLM applications."}
        },
        {
            "inputs": {"question": "What does LANGCHAIN_TRACING_V2 do?"},
            "outputs": {"expected": "Enables automatic tracing of LangChain and LangGraph executions to LangSmith."}
        },
        {
            "inputs": {"question": "How do you trace a plain python function in LangSmith?"},
            "outputs": {"expected": "By decorating the function with @traceable."}
        }
    ]

    client.create_examples(
        inputs=[ex["inputs"] for ex in examples],
        outputs=[ex["outputs"] for ex in examples],
        dataset_id=dataset.id
    )
    print(f"[SUCCESS] Added {len(examples)} benchmark examples to dataset.")
    return dataset


# ------------------------------------------------------------------------------
# 2. Define Custom Evaluators
# ------------------------------------------------------------------------------
def evaluate_contains_keywords(run, example) -> EvaluationResult:
    """Evaluates if target output contains essential expected keywords."""
    prediction = run.outputs.get("output", "") if run.outputs else ""
    expected = example.outputs.get("expected", "")

    # Check key concepts
    score = 1.0 if any(word.lower() in prediction.lower() for word in expected.split()[:3]) else 0.0

    return EvaluationResult(
        key="keyword_relevance",
        score=score,
        comment="Evaluated prediction against expected context."
    )


def evaluate_conciseness(run, example) -> EvaluationResult:
    """Evaluates whether prediction is concise (< 150 words)."""
    prediction = run.outputs.get("output", "") if run.outputs else ""
    word_count = len(prediction.split())
    is_concise = word_count <= 150
    
    return EvaluationResult(
        key="conciseness",
        score=1.0 if is_concise else 0.5,
        comment=f"Word count: {word_count} words."
    )


# ------------------------------------------------------------------------------
# 3. Target Local Model/Chain to Evaluate (Local Ollama)
# ------------------------------------------------------------------------------
def target_qa_chain(inputs: dict) -> dict:
    """The application pipeline target being evaluated using local qwen3:8b."""
    question = inputs["question"]
    
    llm = ChatOllama(model="qwen3:8b", temperature=0.2)
    prompt = ChatPromptTemplate.from_messages([
        ("system", "Answer the user question accurately and concisely in 1-2 sentences."),
        ("user", "{question}")
    ])
    chain = prompt | llm | StrOutputParser()
    
    answer = chain.invoke({"question": question})
    return {"output": answer}


# ------------------------------------------------------------------------------
# 4. Main Evaluation Runner
# ------------------------------------------------------------------------------
def main():
    api_key = os.getenv("LANGCHAIN_API_KEY")
    if not api_key:
        print("[ERROR] LANGCHAIN_API_KEY is required to run LangSmith dataset evaluations.")
        print("Please add your key in .env file before running this script.")
        return

    client = Client()
    create_or_get_dataset(client)

    print("\n[EVAL] Running automated evaluations on dataset with local Ollama & LangSmith...")
    eval_results = evaluate(
        target_qa_chain,
        data=DATASET_NAME,
        evaluators=[evaluate_contains_keywords, evaluate_conciseness],
        experiment_prefix="qwen3-8b-qa-experiment",
        metadata={"model": "qwen3:8b", "infrastructure": "local_ollama", "eval_version": "v1.0"}
    )

    print("\n[SUCCESS] Evaluation complete!")
    print(f"[BENCHMARK] Experiment results uploaded to LangSmith. View benchmarks under Dataset '{DATASET_NAME}'.")

if __name__ == "__main__":
    main()
